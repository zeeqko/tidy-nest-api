CREATE TABLE Inventories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    userId BIGINT NOT NULL REFERENCES Users (id) ON UPDATE CASCADE ON DELETE CASCADE,
    name TEXT NOT NULL,
    imageURL TEXT,
    expiryDate DATE,
    opensOn DATE,
    purchaseDate DATE,
    subCategoryId BIGINT REFERENCES SubCategories (id) ON UPDATE CASCADE ON DELETE SET NULL,
    tagId BIGINT REFERENCES ItemTags (id) ON UPDATE CASCADE ON DELETE SET NULL,
    quantity INTEGER NOT NULL DEFAULT 1,
    unitPrice NUMERIC(10, 2),
    storageLocation TEXT,
    notes TEXT,
    createdAt TIMESTAMPTZ NOT NULL,
    updatedAt TIMESTAMPTZ NOT NULL
);
