CREATE TABLE Looks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    userId BIGINT NOT NULL REFERENCES Users (id) ON UPDATE CASCADE ON DELETE CASCADE,
    name TEXT NOT NULL,
    occasion TEXT,
    createdAt TIMESTAMPTZ NOT NULL,
    updatedAt TIMESTAMPTZ NOT NULL
);

CREATE TABLE LookItems (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lookId BIGINT NOT NULL REFERENCES Looks (id) ON DELETE CASCADE,
    inventoryId BIGINT NOT NULL REFERENCES Inventories (id) ON UPDATE CASCADE ON DELETE CASCADE,
    x DOUBLE PRECISION NOT NULL,
    y DOUBLE PRECISION NOT NULL,
    width DOUBLE PRECISION NOT NULL,
    height DOUBLE PRECISION NOT NULL,
    rotation DOUBLE PRECISION NOT NULL,
    zIndex INTEGER NOT NULL
);

CREATE INDEX lookitems_lookid_idx ON LookItems (lookId);
